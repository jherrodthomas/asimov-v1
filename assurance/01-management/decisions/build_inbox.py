REPO_URL = "https://github.com/jherrodthomas/asimov-v1"


def inline_md(text: str) -> str:
  """Escape text, then turn **bold** into <b>."""
  out = html.escape(" ".join(str(text).split()), quote=False)
  return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", out)


def iso(v) -> str | None:
  d = check_decisions.as_date(v)
  return d.isoformat() if d else None


def ref_url(ref: str) -> str | None:
  ref = str(ref)
  if ref.startswith("https://"):
    return ref
  if re.fullmatch(r"[0-9a-f]{7,40}", ref):
    return f"{REPO_URL}/commit/{ref}"
  m = re.fullmatch(r"#?(\d+)", ref)
  return f"{REPO_URL}/pull/{m.group(1)}" if m else None


def page_entry(d: dict, base: Path) -> dict:
  ans = d.get("answer") or {}
  ap = d.get("applied") or {}
  ex = d.get("explanation") or {}
  return {
    "id": d["id"],
    "ref": d.get("ref", ""),
    "q": html.escape(d["question"], quote=False),
    "why": inline_md(d["context"]),
    "rev": d["reversibility"],
    "blocks": html.escape(d["blocks"], quote=False),
    "gate": d["gate"],
    "asked": iso(d["asked"]),
    "proceedAfter": iso(d.get("proceed_after")),
    "svg": (base / d["figure"]).read_text(encoding="utf-8").strip() if d.get("figure") else "",
    "cap": inline_md(d.get("caption", "")),
    "opts": [{"k": o["key"], "t": html.escape(o["title"], quote=False), "d": inline_md(o["detail"]),
              "rec": bool(o.get("recommended"))} for o in d["options"]],
    "src": [html.escape(str(s), quote=False) for s in d.get("sources", [])],
    "status": d["status"],
    "batch": d.get("batch"),
    "answer": {"choice": ans.get("choice"), "via": ans.get("via"), "at": iso(ans.get("at")),
               "note": html.escape(str(ans.get("note", "")), quote=False)} if ans else None,
    "applied": {"ref": html.escape(str(ap.get("ref")), quote=False), "url": ref_url(ap.get("ref", "")),
                "record": html.escape(str(ap.get("record")), quote=False), "at": iso(ap.get("at"))} if ap else None,
    "explanation": {"text": inline_md(ex.get("text", "")), "at": iso(ex.get("at"))} if ex else None,
    "note": html.escape(str(d.get("note", "")), quote=False),
  }


def queue_entry(d: dict) -> dict:
  rec = next(o for o in d["options"] if o.get("recommended"))
  return {"id": d["id"], "q": html.escape(d["question"], quote=False), "gate": d.get("gate") or "",
          "claude": d.get("decider") == "claude", "after": d.get("after") or [],
          "blocks": html.escape(d["blocks"], quote=False), "rec": html.escape(rec["title"], quote=False)}


def build(entries: list[dict], base: Path = HERE) -> str:
  data = [page_entry(d, base) for d in entries if d["status"] != "queued"]
  queue = [queue_entry(d) for d in entries if d["status"] == "queued"]
  payload = json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/")
  qpayload = json.dumps(queue, ensure_ascii=False).replace("</", "<\\/")
  return (TEMPLATE.replace("/*__REGISTER__*/[]", payload).replace("/*__QUEUE__*/[]", qpayload)
          .replace("__BUILT__", dt.date.today().isoformat()))


def main(argv: list[str]) -> int:
  ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  ap.add_argument("--out", required=True, type=Path)
  ap.add_argument("--register", type=Path, default=check_decisions.REGISTER)
  args = ap.parse_args(argv)
  entries = check_decisions.load(args.register)
  errs = check_decisions.check(entries, args.register.parent)
  if errs:
    print("\n".join(errs))
    return 1
  args.out.write_text(build(entries, args.register.parent), encoding="utf-8")
  print(f"wrote {args.out} ({len(entries)} decisions)")
  return 0


