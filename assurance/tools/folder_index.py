SUBFOLDER_NOTES = {
  "decisions": "Decision register", "figures": "Figure generators (fig_*.py, with --check) and their generated SVGs", "reviews": "Verification review records",
  "impact": "Change impact analysis records", "confirmation": "Confirmation measure records", "gates": "Gate review records and generated skeletons",
  "test-sites": "Test areas and session logs", "parameters": "Safety parameter sets (WP-W-09)",
}


def load_rows() -> dict[str, list[tuple[str, str, str, str, str]]]:
  """folder -> [(id, link, name, gate, status)] from the §3 tables of WP-M-00."""
  out: dict[str, list] = {}
  folder = None
  for line in REGISTER.read_text(encoding="utf-8").splitlines():
    m = re.match(r"^### 3\.\d+ .* \(`([^`]+)/`\)", line)
    if m:
      folder = m.group(1)
      continue
    m = re.match(r"^\| \[(WP-[A-Z]-\d\d)\]\(([^)]+)\) \|", line)
    if m and folder:
      c = [x.strip() for x in line.strip().strip("|").split("|")]
      if len(c) != 9:
        raise SystemExit(f"WP-M-00 row {m.group(1)}: expected 9 columns, found {len(c)}")
      out.setdefault(folder, []).append((m.group(1), m.group(2), c[1], c[7], c[8]))
  return out


def render(folder: str, rows: list[tuple[str, str, str, str, str]]) -> str:
  desc, clauses = FOLDERS[folder]
  lines = [NOTE, "", f"# {folder}", "", desc, "", f"Standard clauses: {clauses}", "",
           "## Work products", "", "| ID | Work product | Gate | Status |", "|---|---|---|---|"]
  for wp, link, name, gate, status in rows:
    rel = link
    if rel.startswith("../" + folder + "/"):
      rel = rel[len(folder) + 4:]
    elif rel.startswith("../"):
      pass  # a work product that lives in another folder (WP-P-11 in process/)
    lines.append(f"| [{wp}]({rel}) | {name} | {gate} | {STATUS.get(status, status)} |")
  subs = sorted(p for p in (ASSURANCE / folder).iterdir() if p.is_dir() and not p.name.startswith((".", "__")))
  if subs:
    lines += ["", "## Subfolders", "", "| Folder | What it holds |", "|---|---|"]
    for p in subs:
      target = f"{p.name}/README.md" if (p / "README.md").exists() else f"{p.name}/"
      lines.append(f"| [`{p.name}/`]({target}) | {SUBFOLDER_NOTES.get(p.name, '—')} |")
  lines += ["", "Drawn from [WP-M-00 §3](../01-management/WP-M-00-work-product-register.md#3-register), which also has the clauses of each work product. Each work product states its own status in its document-control header; this table repeats the register's status column.", ""]
  return "\n".join(lines)


def main(argv: list[str]) -> int:
  rows = load_rows()
  problems = []
  for folder, items in rows.items():
    for wp, link, *_ in items:
      if not (REGISTER.parent / link).resolve().exists():
        problems.append(f"{wp}: registered file does not exist: {link}")
  files = {ASSURANCE / folder / "README.md": render(folder, rows[folder]) for folder in FOLDERS if folder in rows}
  if "--check" in argv:
    for p, text in files.items():
      if not p.exists() or p.read_text(encoding="utf-8") != text:
        problems.append(f"{p.relative_to(ASSURANCE)}: stale or missing; run folder_index.py")
    for p in problems:
      print(p)
    if problems:
      return 1
    print(f"folder indexes current: {len(files)} folders, {sum(len(v) for v in rows.values())} work products registered")
    return 0
  for p in problems:
    print(p)
  for p, text in files.items():
    p.write_text(text, encoding="utf-8")
    print(f"wrote {p.relative_to(ASSURANCE)}")
  return 1 if problems else 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
