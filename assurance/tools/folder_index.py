#!/usr/bin/env python3
"""Generate the README of each numbered assurance folder from the work product register (WP-M-00 §3).

Each folder README lists the folder's work products with gate and status, read from the register, and the
subfolders present on disk. It is generated so the folder pages cannot disagree with the register.

Usage: python3 assurance/tools/folder_index.py           # write the READMEs
       python3 assurance/tools/folder_index.py --check   # fail if a committed README is stale or a registered file is missing
"""
